#!/usr/bin/env python3
"""Recover MinecraftPacketIds -> packet class from MinecraftPackets::createPacket.

createPacket (0x189f8f0) decrements the id, bounds it against 0x72 and jumps
through a table of signed 32-bit offsets relative to the table at 0x2824874.
Each case constructs one packet with std::make_unique<XPacket>. This script
reads the table from the ELF and names each case by the first make_unique call
reachable from its target, writing reverse/evidence/packet_ids.json.
"""
import argparse, hashlib, json, re, struct, subprocess
from pathlib import Path

EXPECTED = '69142612b2a87b0ff6d63f64dd0f07ca94d647b09659590fdadc0900af41c4ad'
FUNCTION, SIZE = 0x189f8f0, 0x1549
TABLE, ENTRIES = 0x2824874, 0x73  # ids 1..0x73; 0 and larger ids return null
DEFAULT = 0x18a0e19  # `ja` target at 0x189f923: no packet constructed

parser = argparse.ArgumentParser()
parser.add_argument('binary', type=Path)
parser.add_argument('--output', type=Path, default=Path('reverse/evidence/packet_ids.json'))
parser.add_argument('--header', type=Path, default=Path('include/bds/network/packet_ids.hpp'))
args = parser.parse_args()
blob = args.binary.read_bytes()
digest = hashlib.sha256(blob).hexdigest()
if digest != EXPECTED:
    raise SystemExit('Unexpected binary hash; review target before analysis')

phoff = struct.unpack_from('<Q', blob, 32)[0]
phsize, phcount = struct.unpack_from('<HH', blob, 54)


def offset(va, width):
    for i in range(phcount):
        kind, _, file_offset, address, _, filesz, _, _ = struct.unpack_from('<IIQQQQQQ', blob, phoff + i * phsize)
        if kind == 1 and address <= va and va + width <= address + filesz:
            return file_offset + va - address
    raise ValueError(f'unmapped address {va:#x}')


text = subprocess.check_output(['objdump', '-d', '-C', '--no-show-raw-insn', f'--start-address={FUNCTION}',
                                f'--stop-address={FUNCTION + SIZE}', str(args.binary)], text=True)
constructions = []
for line in text.splitlines():
    match = re.search(r'^\s*([0-9a-f]+):.*\bcall\s+[0-9a-f]+ <std::_MakeUniq<(\w+)>', line)
    if match:
        constructions.append((int(match[1], 16), match[2]))

packets = []
for index in range(ENTRIES):
    relative = struct.unpack_from('<i', blob, offset(TABLE + 4 * index, 4))[0]
    target = (TABLE + relative) & 0xffffffffffffffff
    if target == DEFAULT:
        packets.append({'id': index + 1, 'hex': f'{index + 1:#04x}', 'class': None, 'case_target': f'{target:#x}'})
        continue
    following = [c for c in constructions if c[0] >= target]
    if not (FUNCTION <= target < FUNCTION + SIZE) or not following:
        raise SystemExit(f'case {index + 1:#x} target {target:#x} not understood')
    site, name = following[0]
    # The first construction reachable from the case target is that case's packet.
    packets.append({'id': index + 1, 'hex': f'{index + 1:#04x}', 'class': name,
                    'case_target': f'{target:#x}', 'construction_site': f'{site:#x}'})

result = {'sha256': digest, 'confidence': 'VERIFIED_BINARY',
          'source': {'function': 'MinecraftPackets::createPacket(MinecraftPacketIds)', 'address': f'{FUNCTION:#x}',
                     'size': f'{SIZE:#x}', 'jump_table': f'{TABLE:#x}', 'entries': ENTRIES,
                     'bounds_check': 'dec %esi; sub $0x72 at 0x189f901/0x189f905; ja default'},
          'unassigned_ids': [p['id'] for p in packets if p['class'] is None],
          'packets': [p for p in packets if p['class'] is not None]}
args.output.write_text(json.dumps(result, indent=2) + '\n')
print(json.dumps({'packets': len(result['packets']), 'unassigned': result['unassigned_ids'], 'output': str(args.output)}))

# Generated C++ identifiers: class names without the Packet suffix.
lines = ['// Generated by reverse/scripts/packet_ids.py from reverse/evidence/packet_ids.json.',
         '// Do not edit by hand. Source: MinecraftPackets::createPacket ' + f'{FUNCTION:#x}' + ', BDS 1.6.0.15 Linux.',
         '#pragma once', '#include <array>', '#include <cstdint>', '#include <string_view>', '',
         'namespace bds::protocol {', 'enum class PacketId : std::uint16_t {']
for packet in result['packets']:
    lines.append(f"    {packet['class'].removesuffix('Packet')} = {packet['hex']},")
lines += ['};', f"inline constexpr std::uint16_t max_packet_id = {ENTRIES:#04x};", '',
          '// Empty for ids createPacket does not construct.',
          'inline constexpr std::string_view packet_name(std::uint16_t id) {',
          f'    constexpr std::array<std::string_view, {ENTRIES + 1}> names{{']
by_id = {p['id']: p['class'] for p in result['packets']}
for i in range(ENTRIES + 1):
    lines.append(f'        "{by_id.get(i, "")}",')
lines += ['    };', '    return id < names.size() ? names[id] : std::string_view{};', '}', '} // namespace bds::protocol', '']
args.header.write_text('\n'.join(lines))
