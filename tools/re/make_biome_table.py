#!/usr/bin/env python3
"""Generate src/world/biome_data.cpp from the original's biome registry dump.

Input: tests/reference/biomes_bds_1.6.0.15.json, written by
tools/re/gdb_terrain_oracle.py (Biome::mBiomes 0x348b670 read from the running
original). The table keeps, per id: name, temperature (+0x34), downfall
(+0x38), depth (+0x4c), scale (+0x50), snow (+0x3c > 0, Biome::isSnowCovered
0x1dc1ae0), the BiomeType object (+0x80, compared by address in
Biome::isSame 0x1dc1a40), the class (from the vtable) and the MutatedBiome
parent (+0xc0).
"""
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLASSES = {  # vtable address (+0x10) -> class, from nm "vtable for X"
    0x31e9388: "Beach", 0x31e8720: "Ocean", 0x31e7ad8: "River", 0x31e80e0: "Swamp", 0x31e7f70: "Taiga",
    0x31e8fa8: "Desert", 0x31e8910: "Forest", 0x31e9488: "Jungle", 0x31e9290: "Nether", 0x31e9120: "Plains",
    0x31e7e70: "TheEnd", 0x31e85a0: "Mutated", 0x31e8b80: "Savanna", 0x31e8240: "OceanCold",
    0x31e7ce0: "OceanWarm", 0x31e83e0: "Overworld", 0x31e8a78: "StoneBeach", 0x31e9600: "OceanFrozen",
    0x31e7870: "ExtremeHills", 0x31e7be0: "OceanLukewarm", 0x31e79d8: "MushroomIsland", 0x31e8818: "Biome",
    0x31e8ce0: "Ice", 0x31e8e50: "Mesa"}


def f32(value):
    return "std::bit_cast<float>(0x%08xU)" % struct.unpack("<I", struct.pack("<f", value))[0]


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tests/reference/biomes_bds_1.6.0.15.json"
    biomes = json.loads(source.read_text())
    types = {}
    rows = []
    for entry in biomes:
        if entry is None:
            continue
        raw = bytes.fromhex(entry["raw"])
        snow = struct.unpack("<f", raw[0x3c:0x40])[0] > 0.0
        kind = CLASSES[int(entry["vtable"], 16)]
        type_index = types.setdefault(entry["type"], len(types))
        rows.append('    {%d, "%s", %s, %s, %s, %s, %s, %d, BiomeClass::%s, %d},' % (
            entry["id"], entry["name"], f32(entry["temperature"]), f32(entry["downfall"]), f32(entry["depth"]),
            f32(entry["scale"]), "true" if snow else "false", type_index, kind, entry.get("parent", -1)))
    out = ROOT / "src/world/biome_data.cpp"
    out.write_text("""// Generated by tools/re/make_biome_table.py from the original's Biome::mBiomes
// registry (tests/reference/biomes_bds_1.6.0.15.json). Do not edit by hand.
#include "bds/world/biome.hpp"
#include <bit>

namespace bds {
const std::vector<BiomeData> &biome_registry() {
    static const std::vector<BiomeData> table{
%s
    };
    return table;
}
} // namespace bds
""" % "\n".join(rows))
    print(f"{len(rows)} biomes, {len(types)} types -> {out}")


if __name__ == "__main__":
    main()
