#!/usr/bin/env python3
"""Write src/world/block_data.cpp from tests/reference/blocks_bds_1.6.0.15.json.

The JSON is the BlockLegacy registry the original holds at run time
(gdb_postprocess_oracle.py, BlockTypeRegistry::mBlockLookupMap 0x34a9340):
per legacy its class and raw bytes. The fields kept are the ones the
generation code reads (offsets from the accessors):

- BlockLegacy +0x58 BlockProperty bits (BlockLegacy::hasProperty 0x1e54db0);
- BlockLegacy +0xaa solid (BlockLegacy::isSolid 0x1e54ab0);
- BlockLegacy +0xb4 light block (Block::getLight 0x1e68a90),
  +0xb5 light emission (BlockLegacy::getLightEmission 0x1e248b0);
- Material (BlockLegacy +0x78, getMaterial 0x1e53630): +0 MaterialType,
  +7 replaceable, +8 liquid, +0xc translucency (float), +0x10 blocks
  motion, +0x12 solid (Material::isReplaceable/isLiquid/getTranslucency/
  getBlocksMotion/isSolid 0x1c56cf0..0x1c56d70);
- the results of no-argument BlockLegacy virtuals called by the oracle:
  +0x160 canContainLiquid (Block::canContainLiquid 0x1abb340).
"""
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tests/reference/blocks_bds_1.6.0.15.json"
    rows = json.loads(source.read_text())
    lines = []
    for row in rows:
        if "raw" not in row:
            continue
        raw = bytes.fromhex(row["raw"])
        properties = struct.unpack_from("<Q", raw, 0x58)[0]
        solid = raw[0xaa] & 1
        light_block, light_emission = raw[0xb4], raw[0xb5]
        m = bytes.fromhex(row["material"])
        mtype = struct.unpack_from("<i", m, 0)[0]
        translucency = struct.unpack_from("<f", m, 0xc)[0]
        virtuals = row.get("virtuals", {})
        lines.append('    {"%s", "%s", 0x%xULL, %d, %d, %d, %d, %d, %d, %d, %d, %d, %sf, %d},' % (
            row["legacy_name"], row["class"] or "", properties, solid, light_block, light_emission, mtype,
            m[7] & 1, m[8] & 1, m[0x10] & 1, m[0x12] & 1, m[5] & 1, repr(float(translucency)),
            virtuals.get("0x160", 0)))
    out = ROOT / "src/world/block_data.cpp"
    out.write_text("""// Generated by tools/re/make_block_table.py from
// tests/reference/blocks_bds_1.6.0.15.json (the original's BlockLegacy
// registry, read under gdb). Do not edit.
#include "bds/world/block_info.hpp"

namespace bds {
const std::vector<BlockInfo> &block_infos() {
    static const std::vector<BlockInfo> table = {
""" + "\n".join(lines) + """
    };
    return table;
}
} // namespace bds
""")
    print(f"{len(lines)} blocks -> {out}")


if __name__ == "__main__":
    main()
