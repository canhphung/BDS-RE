#!/usr/bin/env python3
"""Write src/world/decorator_data.cpp from tests/reference/decorators_bds_1.6.0.15.json.

The JSON is every biome's decorator as the original holds it at run time
(gdb_postprocess_oracle.py: OverworldBiome +0xc0, raw bytes 0..0x230 and the
feature objects it points to, kept to their first 0x30 bytes). The fields OverworldDecorator::decorate
0x1da5250 reads:

  +0x1e0 waterlily, +0x1e4 trees (float), +0x1e8 flowers, +0x1ec grass,
  +0x1f0 dead bushes, +0x1f4 mushrooms, +0x1f8 reeds, +0x1fc cactus,
  +0x200 gravel disks, +0x204 sand disks, +0x208 clay, +0x20c, +0x210,
  +0x214 huge mushrooms, +0x218, +0x21c springs (bool), +0x228 subclass data;

and of the features: ClayFeature +0x18 size, SandFeature (+0x10 sand,
+0x18 gravel) +0x20 radius.
"""
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    rows = json.loads((ROOT / "tests/reference/decorators_bds_1.6.0.15.json").read_text())
    lines = []
    for row in rows:
        if "raw" not in row:
            continue
        raw = bytes.fromhex(row["raw"])
        i = lambda o: struct.unpack_from("<i", raw, o)[0]
        m = row["members"]
        member_int = lambda off, field: struct.unpack_from("<i", bytes.fromhex(m[off]["raw"]), field)[0] if off in m else 0
        lines.append("    {%d, \"%s\", %d, %sf, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d}," % (
            row["id"], row["decorator_class"], i(0x1e0), repr(struct.unpack_from("<f", raw, 0x1e4)[0]), i(0x1e8),
            i(0x1ec), i(0x1f0), i(0x1f4), i(0x1f8), i(0x1fc), i(0x200), i(0x204), i(0x208), i(0x20c), i(0x210),
            i(0x214), i(0x218), raw[0x21c] & 1, i(0x228), member_int("0x8", 0x18), member_int("0x10", 0x20),
            member_int("0x18", 0x20)))
    out = ROOT / "src/world/decorator_data.cpp"
    tail = """
const DecoratorData *decorator_data(int biome) {
    for (const auto &d : decorator_table())
        if (d.biome == biome)
            return &d;
    return nullptr;
}"""
    out.write_text("""// Generated by tools/re/make_decorator_table.py from
// tests/reference/decorators_bds_1.6.0.15.json (the original's biome
// decorators, read under gdb). Do not edit.
#include "bds/world/decorator_data.hpp"

namespace bds {
const std::vector<DecoratorData> &decorator_table() {
    static const std::vector<DecoratorData> table = {
""" + "\n".join(lines) + """
    };
    return table;
}""" + tail + """
} // namespace bds
""")
    print(f"{len(lines)} decorators -> {out}")


if __name__ == "__main__":
    main()
