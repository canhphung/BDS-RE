#!/usr/bin/env python3
"""Build a post-process reference from a capture_terrain.py --postprocess run.

For every postProcess call of the timeline (postprocess.jsonl) that ran to
its end, keep: the centre chunk, the state and heightmap of each chunk of
its 3 x 3 area at the call's start, every earlier block write that landed in
the area (from any thread, in time order: other chunks' post-processing),
and the call's own writes. The chunk volumes themselves are regenerated by
the test (they equal the carved BlockVolume, see terrain_reference).

    make_postprocess_reference.py <run dir> <out.json> [max calls | x:z,x:z,...]

"decorate_at" is the index of the call's first write after the Biome::decorate
call; the test requires every write before it to match.
"""
import json
import sys
from pathlib import Path


def main():
    run, out = Path(sys.argv[1]), Path(sys.argv[2])
    select, limit = None, 1 << 30
    if len(sys.argv) > 3:
        if ":" in sys.argv[3]:
            select = [tuple(int(v) for v in item.split(":")) for item in sys.argv[3].split(",")]
        else:
            limit = int(sys.argv[3])
    seed = None
    for dat in (run / "runtime" / "worlds").glob("*/level.dat"):
        data = dat.read_bytes()
        at = data.find(b"RandomSeed")
        seed = int.from_bytes(data[at + 10:at + 14], "little")
    history, active, calls = [], {}, []
    for line in (run / "postprocess.jsonl").read_text().splitlines():
        e = json.loads(line)
        kind = e["e"]
        if kind == "begin":
            cx, cz = e["x"], e["z"]
            area = {(cx + dx, cz + dz) for dx in (-1, 0, 1) for dz in (-1, 0, 1)}
            prior = [w for w in history if (w[0] >> 4, w[2] >> 4) in area]
            active[e["t"]] = {"x": cx, "z": cz, "area": e.get("area", {}), "prior": prior, "writes": []}
        elif kind == "decorate" and e["t"] in active:
            active[e["t"]]["biome"] = e["biome"]
            if "plains_grass" in e:
                active[e["t"]]["plains_grass"] = e["plains_grass"]
            active[e["t"]]["decorate_at"] = len(active[e["t"]]["writes"])
        elif kind == "end" and e["t"] in active:
            call = active.pop(e["t"])
            call.setdefault("decorate_at", len(call["writes"]))
            calls.append(call)
        elif kind == "set":
            w = [e["x"], e["y"], e["z"], e["b"], e["l"]]
            history.append(w)
            if e["t"] in active:
                active[e["t"]]["writes"].append(w)
    if select:
        calls = [c for key in select for c in calls if (c["x"], c["z"]) == key][:len(select)]
    calls = calls[:limit]
    out.write_text(json.dumps({"seed": seed, "generator": "tools/re/capture_terrain.py --postprocess + "
                               "tools/re/make_postprocess_reference.py", "calls": calls}) + "\n")
    print(f"{len(calls)} calls -> {out}")


if __name__ == "__main__":
    main()
