#!/usr/bin/env python3
"""Generate src/network/block_palette_282.inc (block registry order) from a captured palette.

    python3 tools/reference/make_palette_source.py palette.json SEED

The original BDS 1.6.0.15 builds its network block palette in
BlockPalette::initFromBlockDefinitions (0x1d3c0a0): every block state in
BlockTypeRegistry order, then std::shuffle with Level::getRandom(), a Random
seeded with LevelSettings::getSeed() (Level::Level 0x1c8038f), then runtime id =
index. The palette in a StartGame capture of a freshly created world (seed =
StartGame's seed) is unshuffled here with the same Random (MT19937 with the
original's seeding) and libstdc++'s classic shuffle, giving the registry order.
BDS-RE shuffles it again at start-up with its own level seed.
"""
import json
import sys
from pathlib import Path


class Random:
    # bds::Random / original Random: MT19937 (init_genrand seeding).
    def __init__(self, seed):
        self.mt = [0] * 624
        self.mt[0] = seed & 0xFFFFFFFF
        for i in range(1, 624):
            self.mt[i] = (1812433253 * (self.mt[i - 1] ^ (self.mt[i - 1] >> 30)) + i) & 0xFFFFFFFF
        self.index = 624

    def next_uint(self):
        if self.index >= 624:
            for i in range(624):
                y = (self.mt[i] & 0x80000000) | (self.mt[(i + 1) % 624] & 0x7FFFFFFF)
                self.mt[i] = self.mt[(i + 397) % 624] ^ (y >> 1) ^ (0x9908B0DF if y & 1 else 0)
            self.index = 0
        y = self.mt[self.index]
        self.index += 1
        y ^= y >> 11
        y ^= (y << 7) & 0x9D2C5680
        y ^= (y << 15) & 0xEFC60000
        y ^= y >> 18
        return y


def shuffle_permutation(n, seed):
    # std::shuffle (classic Fisher-Yates) with uniform_int_distribution<unsigned long>.
    r = Random(seed)
    v = list(range(n))
    for i in range(1, n):
        buckets = i + 1
        scaling = 0xFFFFFFFF // buckets
        past = buckets * scaling
        while True:
            x = r.next_uint()
            if x < past:
                break
        j = x // scaling
        v[i], v[j] = v[j], v[i]
    return v


def main():
    data = json.load(open(sys.argv[1]))
    captured = data["entries"] if isinstance(data, dict) and "entries" in data else data["palette"]
    seed = int(sys.argv[2]) & 0xFFFFFFFF
    registry = [None] * len(captured)
    for position, original in enumerate(shuffle_permutation(len(captured), seed)):
        registry[original] = tuple(captured[position])
    assert registry[0] == ("minecraft:air", 0), "not a fresh-world capture with this seed"
    names = sorted({name for name, _ in registry})
    index = {name: i for i, name in enumerate(names)}
    lines = ["// Generated by tools/reference/make_palette_source.py from a StartGame capture of the",
             "// original BDS 1.6.0.15 (protocol 282). Do not edit by hand.",
             "// Block states in BlockTypeRegistry order (before BlockPalette's shuffle).",
             f"// {len(registry)} block states, {len(names)} block names.",
             "static constexpr std::string_view palette_names[] = {"]
    lines += [f'    "{name}",' for name in names]
    lines += ["};", "static constexpr struct { std::uint16_t name; std::int16_t data; } palette_entries[] = {"]
    row = []
    for name, value in registry:
        row.append(f"{{{index[name]}, {value}}}")
        if len(row) == 8:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines += ["};", ""]
    Path("src/network/block_palette_282.inc").write_text("\n".join(lines))
    print(json.dumps({"entries": len(registry), "names": len(names)}))


if __name__ == "__main__":
    main()
