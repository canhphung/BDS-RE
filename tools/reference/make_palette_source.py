#!/usr/bin/env python3
"""Generate src/network/block_palette_282.inc from a captured palette.

    python3 tools/reference/make_palette_source.py input/reference/palette_282.json

The palette comes from StartGame sent by the original BDS 1.6.0.15 (see
analyze_capture.py). Entry order is the original's runtime-id order in that
capture; any order is valid on the wire because the client reads the table.
"""
import json
import sys
from pathlib import Path

entries = json.load(open(sys.argv[1]))["entries"]
names = sorted({name for name, _ in entries})
index = {name: i for i, name in enumerate(names)}
lines = ["// Generated by tools/reference/make_palette_source.py from a StartGame capture of the",
         "// original BDS 1.6.0.15 (protocol 282). Do not edit by hand.",
         f"// {len(entries)} block states, {len(names)} block names.",
         "static constexpr std::string_view palette_names[] = {"]
lines += [f'    "{name}",' for name in names]
lines += ["};", "static constexpr struct { std::uint16_t name; std::int16_t data; } palette_entries[] = {"]
row = []
for name, data in entries:
    row.append(f"{{{index[name]}, {data}}}")
    if len(row) == 8:
        lines.append("    " + ", ".join(row) + ",")
        row = []
if row:
    lines.append("    " + ", ".join(row) + ",")
lines += ["};", ""]
Path("src/network/block_palette_282.inc").write_text("\n".join(lines))
print(json.dumps({"entries": len(entries), "names": len(names)}))
